#!/usr/bin/env node
// Generates redirects.csv, _redirects (Netlify) and the [[redirects]] block in netlify.toml
// from data/redirects-source.json + data/suburbs.json. Run: npm run redirects
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = JSON.parse(fs.readFileSync(path.join(root, 'data/redirects-source.json'), 'utf8'));
const suburbs = JSON.parse(fs.readFileSync(path.join(root, 'data/suburbs.json'), 'utf8'));
const suburbSlugs = new Set(suburbs.map(s => s.slug));

function areaFor(slug) {
  // garden-supplies-in-{suburb}, garden-supplies-{suburb}, with optional -2 suffix
  const m = slug.replace(/-\d+$/, '').match(/^garden-supplies(?:-in)?-(.+)$/);
  if (m && suburbSlugs.has(m[1])) return `/areas/${m[1]}/`;
  return '/areas/';
}

function mapSlug(slug) {
  if (src.explicit[slug] !== undefined) return { to: src.explicit[slug], rule: 'explicit' };
  for (const [kw, to] of src.keywordRules) {
    if (slug.includes(kw)) return { to: to === 'AREA' ? areaFor(slug) : to, rule: `keyword:${kw}` };
  }
  return { to: '/', rule: 'fallback' };
}

const rows = [];
const seen = new Set();
for (const slug of src.oldSlugs) {
  if (seen.has(slug)) continue; seen.add(slug);
  const { to, rule } = mapSlug(slug);
  rows.push({ from: `/${slug}`, to, rule });
}
// author archive + WordPress leftovers
rows.push({ from: '/author/*', to: '/', rule: 'author-noindex' });
rows.push({ from: '/feed', to: '/', rule: 'wp' });
rows.push({ from: '/comments/feed', to: '/', rule: 'wp' });
rows.push({ from: '/wp-json/*', to: '/', rule: 'wp' });
rows.push({ from: '/wp-content/uploads/*', to: '/', rule: 'wp' });

// redirects.csv
const csv = ['old_path,new_path,status,rule']
  .concat(rows.map(r => `${r.from},${r.to},301,${r.rule}`)).join('\n') + '\n';
fs.writeFileSync(path.join(root, 'redirects.csv'), csv);

// _redirects — Netlify matches with/without trailing slash and http→https automatically
// when force (301!) is used. We emit both forms explicitly so no chain is possible.
const lines = ['# Generated by scripts/build-redirects.js — do not edit by hand', '',
  '# Force https + canonical host (apex). Netlify handles www→apex at the domain level too.',
  'http://surreyhillsgardensupplies.com.au/* https://surreyhillsgardensupplies.com.au/:splat 301!',
  'http://www.surreyhillsgardensupplies.com.au/* https://surreyhillsgardensupplies.com.au/:splat 301!',
  'https://www.surreyhillsgardensupplies.com.au/* https://surreyhillsgardensupplies.com.au/:splat 301!',
  ''];
for (const r of rows) {
  if (r.from.endsWith('/*')) { lines.push(`${r.from} ${r.to} 301!`); continue; }
  if (r.from === '/' || r.from === '/home') { lines.push(`${r.from} / 301!`); continue; }
  if (r.to === r.from + '/') continue; // same URL, Netlify pretty-urls handles slash
  lines.push(`${r.from} ${r.to} 301!`);
  lines.push(`${r.from}/ ${r.to} 301!`);
}
lines.push('', '# Trailing-slash normalisation for new URLs is handled by Netlify pretty URLs (netlify.toml).');
fs.writeFileSync(path.join(root, 'site/_redirects'), lines.join('\n') + '\n');

// netlify.toml
const toml = `# Surrey Hills Garden Supplies — Netlify config (generated redirects block by scripts/build-redirects.js)
[build]
  publish = "site"
  command = "npm run build"

[build.processing]
  skip_processing = false
[build.processing.html]
  pretty_urls = true

[[headers]]
  for = "/*"
  [headers.values]
    X-Frame-Options = "SAMEORIGIN"
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "strict-origin-when-cross-origin"
    Permissions-Policy = "camera=(), microphone=(), geolocation=()"

[[headers]]
  for = "/assets/*"
  [headers.values]
    Cache-Control = "public, max-age=31536000, immutable"

[[headers]]
  for = "/order/*"
  [headers.values]
    X-Robots-Tag = "noindex, nofollow"

[[headers]]
  for = "/author/*"
  [headers.values]
    X-Robots-Tag = "noindex, nofollow"

# ---- 301 redirects (old WordPress URLs → new URL map). Also in site/_redirects. ----
` + rows.filter(r => !(r.to === r.from + '/')).flatMap(r => {
  const out = [];
  const mk = (from) => `[[redirects]]\n  from = "${from}"\n  to = "${r.to}"\n  status = 301\n  force = true\n`;
  if (r.from.endsWith('/*') || r.from === '/' || r.from === '/home') { out.push(mk(r.from)); }
  else { out.push(mk(r.from)); out.push(mk(r.from + '/')); }
  return out;
}).join('\n');
fs.writeFileSync(path.join(root, 'netlify.toml'), toml);

const counts = rows.reduce((a, r) => { const k = r.rule.split(':')[0]; a[k] = (a[k] || 0) + 1; return a; }, {});
console.log(`redirects: ${rows.length} rows`, counts);
const fallbacks = rows.filter(r => r.rule === 'fallback').map(r => r.from);
if (fallbacks.length) console.log('fallback → / :', fallbacks.join(', '));
